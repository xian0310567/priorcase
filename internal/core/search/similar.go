package search

import (
	"github.com/xian0310567/priorcase/internal/core/config"
	"github.com/xian0310567/priorcase/internal/core/store"
)

// SimilarLimit 은 발췌 하나에 붙이는 대조 결과 수다.
//
// 셋이면 사람이 훑기에 부담이 없고, 실측에서 맞는 노트는 **1위로** 나왔다.
// 늘려도 판정에 쓰이지 않고 화면만 길어진다.
const SimilarLimit = 3

// Similar 는 대화 발췌와 비슷한 기존 결정을 준다.
//
// # 왜 있나
//
// **판별기는 중복 대조를 받는데 사람은 못 받았다.** 자동 승격 경로는 그 도메인의
// 기존 결정 요약을 판별기에게 넘겨 중복을 거르는데(promote.existingSummaries),
// 확인 큐에서 사람이 판정할 때는 아무 도움도 없었다 — 볼트를 맨눈으로 뒤져야 했다.
//
// 실측이 그 비용을 보여 줬다. 확인 큐 7건을 손으로 처리했더니 **4건이 볼트 대조만으로**
// 판정됐다(이미 있음 3 · 결정 아님 1). 그 대조를 붙이면 사람이 실제로 읽을 것이 절반
// 이하로 준다.
//
// # 판정하지 않는다
//
// **"이미 기록됨" 이라고 말하지 않는다. 점수와 함께 보여 주고 사람이 판단한다.**
//
// 실측한 네 발췌의 점수:
//
//	진짜 일치 있음 : 1위 113 / 65 / 83   (2위 대비 1.6~1.7배)
//	일치 없음      : 1위  54            (2위 대비 1.04배)
//
// 절대 점수로는 못 가른다 — 진짜 일치 65 와 가짜 1위 54 가 겹친다. 1위·2위 격차는
// 깔끔히 갈리지만 **표본이 넷뿐이라 문턱으로 쓰지 않는다.** 회수는 언제나 무언가를
// 돌려주므로, 도구가 단정하면 그 단정이 틀렸을 때 사람이 확인을 건너뛴다.
//
// # 발췌를 자르지 않는다
//
// 길이별로 재 보니 400자에서는 맞는 노트를 놓쳤고(순위 0, 격차 1.00) 800자부터
// 안정됐다. 발췌는 이미 3KB 안팎으로 묶여 있으므로 그대로 넘긴다.
//
// 도메인으로 좁히지 않는 것도 측정에 따른 것이다 — 전체를 봐도 맞는 노트가 1위였고,
// 프로젝트를 넘는 교훈은 다른 도메인에 있을 수 있다.
//
// 읽지 못한 노트는 두 번째 값으로 준다. 조용히 짧은 목록을 주면 "비슷한 것이 없다" 와
// "못 봤다" 가 같아 보인다.
func Similar(l *store.Layout, c *config.Config, excerpt string) ([]Hit, []store.SkippedNote, error) {
	return Recall(l, c, excerpt, Options{
		Limit:    SimilarLimit,
		MinScore: 1,
		// Cwd 를 안 준다. 발췌는 그 구간의 것이지 지금 셸이 있는 자리의 것이 아니다 —
		// cwd 도메인에 가산점을 주면 엉뚱한 프로젝트가 위로 올라온다.
		CrossProject: true,
	})
}
